CREATE OR REPLACE VIEW public.analytics_daily_user_activity AS
WITH activity AS (
    SELECT
        (occurred_at AT TIME ZONE 'UTC')::DATE AS activity_date,
        COALESCE(user_id::TEXT, anon_id::TEXT) AS actor_id,
        session_id
    FROM public.app_analytics_events
    WHERE event_name IN (
        'session_started',
        'app_foregrounded',
        'session_ended',
        'screen_view',
        'tab_switched',
        'search_opened',
        'magic_search_submitted',
        'location_saved',
        'location_disliked',
        'bubble_opened'
    )
),
daily AS (
    SELECT
        activity_date,
        COUNT(DISTINCT actor_id) AS dau,
        COUNT(DISTINCT session_id) AS total_sessions
    FROM activity
    GROUP BY activity_date
)
SELECT
    d.activity_date,
    d.dau,
    d.total_sessions,
    ROUND(d.total_sessions::NUMERIC / NULLIF(d.dau, 0), 3) AS sessions_per_active_user,
    (
        SELECT COUNT(DISTINCT a.actor_id)
        FROM activity a
        WHERE a.activity_date BETWEEN d.activity_date - 6 AND d.activity_date
    ) AS wau,
    (
        SELECT COUNT(DISTINCT a.actor_id)
        FROM activity a
        WHERE a.activity_date BETWEEN d.activity_date - 29 AND d.activity_date
    ) AS mau,
    ROUND(
        d.dau::NUMERIC / NULLIF((
            SELECT COUNT(DISTINCT a.actor_id)
            FROM activity a
            WHERE a.activity_date BETWEEN d.activity_date - 29 AND d.activity_date
        ), 0),
        4
    ) AS dau_mau_stickiness,
    ROUND(
        (
            SELECT AVG(user_days.days_active::NUMERIC)
            FROM (
                SELECT
                    a.actor_id,
                    COUNT(DISTINCT a.activity_date) AS days_active
                FROM activity a
                WHERE a.activity_date BETWEEN d.activity_date - 6 AND d.activity_date
                GROUP BY a.actor_id
            ) user_days
        ),
        3
    ) AS avg_active_days_per_user_7d
FROM daily d
ORDER BY d.activity_date DESC;

CREATE OR REPLACE VIEW public.analytics_retention_cohorts AS
WITH activity AS (
    SELECT DISTINCT
        COALESCE(user_id::TEXT, anon_id::TEXT) AS actor_id,
        (occurred_at AT TIME ZONE 'UTC')::DATE AS activity_date
    FROM public.app_analytics_events
    WHERE event_name IN ('session_started', 'app_foregrounded')
),
first_seen AS (
    SELECT
        actor_id,
        MIN(activity_date) AS cohort_date
    FROM activity
    GROUP BY actor_id
)
SELECT
    fs.cohort_date,
    COUNT(*) AS cohort_size,
    COUNT(*) FILTER (
        WHERE EXISTS (
            SELECT 1
            FROM activity a
            WHERE a.actor_id = fs.actor_id
              AND a.activity_date = fs.cohort_date + 1
        )
    ) AS d1_retained_users,
    COUNT(*) FILTER (
        WHERE EXISTS (
            SELECT 1
            FROM activity a
            WHERE a.actor_id = fs.actor_id
              AND a.activity_date = fs.cohort_date + 7
        )
    ) AS d7_retained_users,
    COUNT(*) FILTER (
        WHERE EXISTS (
            SELECT 1
            FROM activity a
            WHERE a.actor_id = fs.actor_id
              AND a.activity_date = fs.cohort_date + 30
        )
    ) AS d30_retained_users,
    ROUND(
        (COUNT(*) FILTER (
            WHERE EXISTS (
                SELECT 1
                FROM activity a
                WHERE a.actor_id = fs.actor_id
                  AND a.activity_date = fs.cohort_date + 1
            )
        ))::NUMERIC / NULLIF(COUNT(*), 0),
        4
    ) AS d1_retention_rate,
    ROUND(
        (COUNT(*) FILTER (
            WHERE EXISTS (
                SELECT 1
                FROM activity a
                WHERE a.actor_id = fs.actor_id
                  AND a.activity_date = fs.cohort_date + 7
            )
        ))::NUMERIC / NULLIF(COUNT(*), 0),
        4
    ) AS d7_retention_rate,
    ROUND(
        (COUNT(*) FILTER (
            WHERE EXISTS (
                SELECT 1
                FROM activity a
                WHERE a.actor_id = fs.actor_id
                  AND a.activity_date = fs.cohort_date + 30
            )
        ))::NUMERIC / NULLIF(COUNT(*), 0),
        4
    ) AS d30_retention_rate
FROM first_seen fs
GROUP BY fs.cohort_date
ORDER BY fs.cohort_date DESC;

CREATE OR REPLACE VIEW public.analytics_feature_adoption_daily AS
SELECT
    (occurred_at AT TIME ZONE 'UTC')::DATE AS activity_date,
    COALESCE(feature_name, event_name) AS feature_name,
    COUNT(*) AS event_count,
    COUNT(DISTINCT COALESCE(user_id::TEXT, anon_id::TEXT)) AS unique_users
FROM public.app_analytics_events
WHERE event_name IN (
    'search_opened',
    'magic_search_submitted',
    'location_card_opened',
    'location_saved',
    'location_disliked',
    'collection_created',
    'bubble_opened'
)
GROUP BY
    (occurred_at AT TIME ZONE 'UTC')::DATE,
    COALESCE(feature_name, event_name)
ORDER BY activity_date DESC, feature_name;

CREATE OR REPLACE VIEW public.analytics_notification_funnel_daily AS
WITH base AS (
    SELECT
        (occurred_at AT TIME ZONE 'UTC')::DATE AS activity_date,
        event_name,
        COALESCE(user_id::TEXT, anon_id::TEXT) AS actor_id,
        properties
    FROM public.app_analytics_events
    WHERE event_name IN (
        'notification_permission_prompted',
        'notification_permission_result',
        'notification_received',
        'notification_opened',
        'deep_link_routed',
        'deep_link_failed'
    )
)
SELECT
    activity_date,
    COUNT(*) FILTER (WHERE event_name = 'notification_permission_prompted') AS permission_prompted,
    COUNT(*) FILTER (
        WHERE event_name = 'notification_permission_result'
          AND COALESCE(properties->>'status', '') IN ('authorized', 'provisional')
    ) AS permission_enabled_events,
    COUNT(*) FILTER (WHERE event_name = 'notification_received') AS notifications_received,
    COUNT(*) FILTER (WHERE event_name = 'notification_opened') AS notifications_opened,
    COUNT(*) FILTER (WHERE event_name = 'deep_link_routed') AS deep_link_routed,
    COUNT(*) FILTER (WHERE event_name = 'deep_link_failed') AS deep_link_failed,
    COUNT(DISTINCT actor_id) FILTER (WHERE event_name = 'notification_received') AS users_received,
    COUNT(DISTINCT actor_id) FILTER (WHERE event_name = 'notification_opened') AS users_opened,
    ROUND(
        (COUNT(*) FILTER (WHERE event_name = 'notification_opened'))::NUMERIC
        / NULLIF(COUNT(*) FILTER (WHERE event_name = 'notification_received'), 0),
        4
    ) AS open_rate
FROM base
GROUP BY activity_date
ORDER BY activity_date DESC;

