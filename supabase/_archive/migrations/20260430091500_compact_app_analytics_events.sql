DROP VIEW IF EXISTS public.analytics_retention_cohorts;
DROP VIEW IF EXISTS public.analytics_feature_adoption_daily;
DROP VIEW IF EXISTS public.analytics_notification_funnel_daily;

CREATE TABLE IF NOT EXISTS public.app_analytics_events_v2 (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    event_name TEXT NOT NULL,
    session_id TEXT NOT NULL,
    user_id UUID REFERENCES public.users (supabase_id) ON DELETE SET NULL,
    anon_id UUID,
    feature_name TEXT,
    properties JSONB,
    CONSTRAINT app_analytics_events_v2_event_name_snake_case_chk CHECK (
        event_name ~ '^[a-z][a-z0-9_]*$'
    ),
    CONSTRAINT app_analytics_events_v2_actor_presence_chk CHECK (
        user_id IS NOT NULL OR anon_id IS NOT NULL
    )
);

TRUNCATE TABLE public.app_analytics_events_v2;

INSERT INTO public.app_analytics_events_v2 (
    occurred_at,
    event_name,
    session_id,
    user_id,
    anon_id,
    feature_name,
    properties
)
SELECT
    occurred_at,
    event_name,
    session_id,
    user_id,
    anon_id,
    CASE
        WHEN event_name IN (
            'search_opened',
            'magic_search_submitted',
            'location_card_opened',
            'location_saved',
            'location_disliked',
            'collection_created',
            'bubble_opened'
        ) THEN COALESCE(NULLIF(feature_name, ''), event_name)
        ELSE NULL
    END AS feature_name,
    CASE
        WHEN event_name = 'notification_permission_result'
             AND properties IS NOT NULL
             AND COALESCE(properties->>'status', '') <> ''
        THEN jsonb_build_object('status', properties->>'status')
        ELSE NULL
    END AS properties
FROM public.app_analytics_events
WHERE occurred_at >= NOW() - INTERVAL '45 days'
  AND event_name IN (
      'session_started',
      'app_foregrounded',
      'session_ended',
      'screen_view',
      'tab_switched',
      'search_opened',
      'magic_search_submitted',
      'location_card_opened',
      'location_saved',
      'location_disliked',
      'collection_created',
      'bubble_opened',
      'notification_permission_prompted',
      'notification_permission_result',
      'notification_received',
      'notification_opened',
      'deep_link_routed',
      'deep_link_failed'
  );

