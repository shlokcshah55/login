CREATE OR REPLACE FUNCTION public.track_app_event(
    p_event_name TEXT,
    p_event_category TEXT,
    p_session_id TEXT,
    p_anon_id UUID,
    p_screen_name TEXT,
    p_feature_name TEXT,
    p_duration_ms INT,
    p_occurred_at TIMESTAMPTZ,
    p_app_version TEXT,
    p_build_number TEXT,
    p_platform TEXT,
    p_os_version TEXT,
    p_locale TEXT,
    p_timezone TEXT,
    p_properties JSONB DEFAULT '{}'::JSONB
) RETURNS VOID AS $$
DECLARE
    v_user_id UUID := auth.uid();
    v_event_name TEXT := LOWER(TRIM(COALESCE(p_event_name, '')));
    v_session_id TEXT := TRIM(COALESCE(p_session_id, ''));
    v_feature_name TEXT := NULLIF(TRIM(COALESCE(p_feature_name, '')), '');
    v_properties JSONB := NULL;
BEGIN
    IF v_event_name = '' THEN
        RETURN;
    END IF;

    IF v_event_name !~ '^[a-z][a-z0-9_]*$' THEN
        RETURN;
    END IF;

    IF v_session_id = '' THEN
        RETURN;
    END IF;

    IF v_user_id IS NULL AND p_anon_id IS NULL THEN
        RETURN;
    END IF;

    IF v_event_name NOT IN (
        'session_started',
        'app_foregrounded',
        'session_ended',
        'screen_view',
        'tab_switched',
        'search_opened',
        'magic_search_submitted',
        'location_card_opened',
        'location_saved',
        'location_disliked',
        'collection_created',
        'bubble_opened',
        'notification_permission_prompted',
        'notification_permission_result',
        'notification_received',
        'notification_opened',
        'deep_link_routed',
        'deep_link_failed'
    ) THEN
        RETURN;
    END IF;

    IF v_event_name = 'notification_permission_result' THEN
        IF p_properties IS NOT NULL
           AND COALESCE(p_properties->>'status', '') <> '' THEN
            v_properties := jsonb_build_object(
                'status',
                p_properties->>'status'
            );
        END IF;
    END IF;

    IF v_event_name NOT IN (
        'search_opened',
        'magic_search_submitted',
        'location_card_opened',
        'location_saved',
        'location_disliked',
        'collection_created',
        'bubble_opened'
    ) THEN
        v_feature_name := NULL;
    END IF;

    INSERT INTO public.app_analytics_events (
        occurred_at,
        event_name,
        session_id,
        user_id,
        anon_id,
        feature_name,
        properties
    )
    VALUES (
        COALESCE(p_occurred_at, NOW()),
        v_event_name,
        v_session_id,
        v_user_id,
        p_anon_id,
        v_feature_name,
        v_properties
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

